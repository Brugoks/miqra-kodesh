// Rebuild the locally hosted CC0 surface library. No runtime third-party requests.
// Requires curl and the project's sharp dependency. Run from any directory.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(import.meta.dirname, '..');
const destination = 'public/assets/scenes/bethlehem/materials';
await mkdir(path.join(root, destination), { recursive: true });
const definitions = [
  ['plaster', 'white_plaster_rough_01', 2],
  ['earth', 'dry_ground_rocks', 3],
  ['timber', 'weathered_brown_planks', 2],
  ['rock', 'rock_boulder_dry', 3],
];
const materials = [];
for (const [name, asset, metres] of definitions) {
  const files = JSON.parse(execFileSync('curl', ['-fsSL', `https://api.polyhaven.com/files/${asset}`]));
  const material = {
    id: `bethlehem-${name}`, scale: [metres, metres], roughness: 1, metalness: 0,
    source: `https://polyhaven.com/a/${asset}`, license: 'CC0', maps: {}, files: {},
  };
  for (const [map, key] of [['diffuse', 'Diffuse'], ['normal', 'nor_gl'], ['roughness', 'Rough']]) {
    const sourceUrl = files[key]['1k'].jpg.url;
    const original = execFileSync('curl', ['-fsSL', sourceUrl], { maxBuffer: 16 * 1024 * 1024 });
    const buffer = await sharp(original).resize(1024, 1024, { fit: 'fill' })
      .webp({ quality: map === 'normal' ? 94 : 85, effort: 6 }).toBuffer();
    const hash = createHash('sha256').update(buffer).digest('hex').slice(0, 8);
    const filename = `${name}-${map}-${hash}.webp`;
    await writeFile(path.join(root, destination, filename), buffer);
    material.maps[map] = `/assets/scenes/bethlehem/materials/${filename}`;
    material.files[map] = { sourceUrl, hash, size: buffer.length };
  }
  materials.push(material);
}
await writeFile(path.join(root, 'src/components/scene/bethlehemMaterialAssets.js'),
  '// Generated by scripts/prepare-bethlehem-materials.mjs. Poly Haven assets: CC0.\n'
  + `export const BETHLEHEM_MATERIAL_ASSETS = ${JSON.stringify(materials, null, 2)};\n`);
console.log(`Prepared ${materials.length} material sets (${materials.reduce((n, m) => n + Object.values(m.files).reduce((s, f) => s + f.size, 0), 0)} bytes).`);
