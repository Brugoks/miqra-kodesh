// Generates src/lib/versification.js (verses per chapter) from scripts/kjv-en.json.
//
//   node scripts/build-versification.js
//
// kjv-en.json is an array of the 66 books in canonical order, each shaped
// { abbrev, chapters: [[verseText, …], …] }, so verse counts are just the
// per-chapter array lengths. The script asserts that the chapter counts it
// derives match BOOK_CHAPTERS before writing anything — if that check fails the
// source file is not what we think it is and the output would be silently wrong.

import { readFileSync, writeFileSync } from 'node:fs';
import { BOOK_CHAPTERS, CANONICAL_ORDER } from '../src/lib/scripture.js';

const SOURCE = new URL('./kjv-en.json', import.meta.url);
const OUTPUT = new URL('../src/lib/versification.js', import.meta.url);

const books = JSON.parse(readFileSync(SOURCE, 'utf8'));

if (books.length !== CANONICAL_ORDER.length) {
  throw new Error(`Expected ${CANONICAL_ORDER.length} books in kjv-en.json, found ${books.length}`);
}

const key = (code) => (/^\d/.test(code) ? `'${code}'` : code);
const rows = [];

books.forEach((book, i) => {
  const code = CANONICAL_ORDER[i];
  const counts = book.chapters.map((chapter) => chapter.length);
  if (counts.length !== BOOK_CHAPTERS[code]) {
    throw new Error(`${code}: kjv-en.json has ${counts.length} chapters, BOOK_CHAPTERS says ${BOOK_CHAPTERS[code]}`);
  }
  if (counts.some((n) => !Number.isInteger(n) || n < 1)) {
    throw new Error(`${code}: found a chapter with no verses`);
  }
  rows.push(`  ${key(code)}: [${counts.join(',')}],`);
});

const total = books.reduce((sum, book) => sum + book.chapters.reduce((n, c) => n + c.length, 0), 0);

const file = `// Verses per chapter, indexed by USFM book code — BOOK_VERSES.GEN[0] is Genesis 1.
//
// GENERATED by scripts/build-versification.js from scripts/kjv-en.json.
// Do not hand-edit; re-run the script instead.
//
// Deliberately its own module rather than part of scripture.js: scripture.js is
// pulled into the main bundle by the app-wide scriptureLinker, while this table
// is only needed by the lazily-loaded Scripture Lookup panel.
//
// Versification varies between translations — modern ones omit verses the KJV
// carries (Matthew 17:21, Acts 8:37, John 5:4, …) and Hebrew Psalm
// superscriptions shift numbering. This table is an UPPER BOUND used to build
// the verse picker; callers must tolerate a picked verse being absent from the
// translation they loaded. Total verses here: ${total}.
export const BOOK_VERSES = {
${rows.join('\n')}
};

// Verse count for a chapter, or 0 when the book or chapter is unknown.
export function versesIn(code, chapter) {
  const counts = BOOK_VERSES[code];
  if (!counts || !Number.isInteger(chapter) || chapter < 1 || chapter > counts.length) return 0;
  return counts[chapter - 1];
}
`;

writeFileSync(OUTPUT, file);
console.log(`Wrote ${OUTPUT.pathname} — 66 books, ${total} verses.`);
